-- AI output is a candidate, separate from editable and approved plan versions.
CREATE TABLE plan_generation_job (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 org_id VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 created_at DATETIME(6) NOT NULL,
 created_by VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 patient_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 plan_version_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 input_snapshot_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 base_revision BIGINT UNSIGNED NOT NULL,
 data_mode VARCHAR(16) COLLATE utf8mb4_bin NOT NULL,
 idempotency_key VARCHAR(128) COLLATE utf8mb4_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 retry_of_job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 status VARCHAR(24) COLLATE utf8mb4_bin NOT NULL,
 model VARCHAR(100) NOT NULL,
 prompt_version VARCHAR(64) NOT NULL,
 rule_version VARCHAR(64) NOT NULL,
 system_prompt TEXT NOT NULL,
 model_input_json JSON NOT NULL,
 raw_output MEDIUMTEXT NULL,
 candidate_json JSON NULL,
 issues_json JSON NULL,
 usage_json JSON NULL,
 provider_request_id VARCHAR(200) NULL,
 error_code VARCHAR(64) NULL,
 started_at DATETIME(6) NULL,
 finished_at DATETIME(6) NULL,
 applied_at DATETIME(6) NULL,
 PRIMARY KEY(id),
 UNIQUE KEY uk_generation_scope(org_id,id),
 UNIQUE KEY uk_generation_idempotency(org_id,created_by,idempotency_key),
 KEY idx_generation_poll(status,created_at),
 KEY idx_generation_version(org_id,plan_version_id,created_at),
 FOREIGN KEY(org_id,patient_id) REFERENCES patient(org_id,id),
 FOREIGN KEY(org_id,plan_version_id) REFERENCES care_plan_version(org_id,id),
 FOREIGN KEY(org_id,input_snapshot_id) REFERENCES health_input_snapshot(org_id,id),
 CHECK(data_mode='DEMO'),
 CHECK(status IN ('PENDING','RUNNING','SUCCEEDED','REJECTED','FAILED','APPLIED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
